#!/bin/bash
# Скрипт для автоматического отключения (комментирования) импортов Tendermint и Terra в Go-файлах

echo "Начинается обработка Go-файлов для отключения Tendermint и Terra..."

# Обходим все файлы с расширением .go в текущей директории и её поддиректориях
find . -type f -name "*.go" | while read file; do
  echo "Обрабатывается: $file"
  # Создаем резервную копию файла (с расширением .bak)
  cp "$file" "$file.bak"
  # Комментируем строки, содержащие "tendermint" (без учета регистра)
  sed -i '/[Tt]endermint/s/^/\/\/ /' "$file"
  # Комментируем строки, содержащие "terra" (без учета регистра)
  sed -i '/[Tt]erra/s/^/\/\/ /' "$file"
done

echo "Обработка завершена."
echo "Пожалуйста, проверьте изменения и запустите 'go mod tidy' для обновления зависимостей (если необходимо)."
